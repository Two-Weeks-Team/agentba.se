import { copyFileSync, cpSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import company from "../data/company.json";
import { getContent, SITE } from "../lib/i18n";
import { renderLlmsTxt, renderMarkdown } from "../lib/machine";
import { LANDING_STYLES, landingStylesheetHref, renderLandingHtml } from "../lib/landing";
import { BROWSER_ICONS, companyGraph, OG_IMAGE_PATH, OG_SIZE, serializeJsonLd } from "../lib/seo";
import { BRAND_APPLE_ICON, BRAND_FAVICON, BRAND_MANIFEST } from "../lib/brand";
import { writeBrandPreview } from "./write-brand-preview";

// Export the production source for local design review. This file is generated;
// the production page never reads from the design-previews directory.
const root = "design-previews/2026-10-10/vision";
const path = join(root, "c.html");
const { meta } = getContent("en");
const escape = (value: string) => value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const tag = (key: string, value: string, property = false) => `  <meta ${property ? "property" : "name"}="${key}" content="${escape(value)}">`;
const link = (rel: string, href: string, extra = "") => `  <link rel="${rel}" href="${href}"${extra}>`;
const head = [
  "  <!-- SEO: generated by pnpm seo:preview -->",
  `  <title>${escape(meta.title)}</title>`,
  tag("description", meta.description),
  tag("robots", "index, follow, max-image-preview:large"),
  link("canonical", `${SITE}/`),
  link("alternate", `${SITE}/`, ' hreflang="en"'),
  link("alternate", `${SITE}/ko`, ' hreflang="ko"'),
  link("alternate", `${SITE}/`, ' hreflang="x-default"'),
  link("alternate", `${SITE}/index.md`, ' type="text/markdown"'),
  link("describedby", `${SITE}/llms.txt`, ' type="text/plain"'),
  ...Object.entries({
    "og:type": "website", "og:site_name": company.name, "og:url": `${SITE}/`,
    "og:locale": "en_US", "og:locale:alternate": "ko_KR",
    "og:title": meta.ogTitle, "og:description": meta.description,
    "og:image": `${SITE}${OG_IMAGE_PATH}`, "og:image:type": "image/png",
    "og:image:width": String(OG_SIZE.width), "og:image:height": String(OG_SIZE.height),
    "og:image:alt": meta.ogAlt,
  }).map(([key, value]) => tag(key, value, true)),
  ...Object.entries({
    "twitter:card": "summary_large_image", "twitter:title": meta.ogTitle,
    "twitter:description": meta.description, "twitter:image": `${SITE}${OG_IMAGE_PATH}`,
    "twitter:image:alt": meta.ogAlt,
  }).map(([key, value]) => tag(key, value)),
  `  <script type="application/ld+json">${serializeJsonLd(companyGraph())}</script>`,
  "  <!-- /SEO -->",
].join("\n");
mkdirSync(root, { recursive: true });
const body = renderLandingHtml().replaceAll('/landing/', 'assets/').replace('href="/llms.txt"', 'href="llms.txt"').replace('href="/index.md"', 'href="index.md"');
const html = `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
${head}
<link rel="icon" href="${BRAND_FAVICON.slice(1)}" type="image/svg+xml" sizes="any">
${BROWSER_ICONS.map(icon => `<link rel="icon" href="${icon.url.slice(1)}" type="${icon.type}" sizes="${icon.sizes}">`).join("\n")}
<link rel="apple-touch-icon" href="${BRAND_APPLE_ICON.slice(1)}" sizes="180x180">
<link rel="manifest" href="${BRAND_MANIFEST.slice(1)}">
${LANDING_STYLES.map(file => `<link rel="stylesheet" href="${landingStylesheetHref(file).replace('/landing/', 'assets/')}">`).join("\n")}
</head><body>${body}<script type="module" src="assets/init.js"></script></body></html>`;
writeFileSync(path, html);
cpSync("assets/landing", join(root, "assets"), { recursive: true });
cpSync("public/icons", join(root, "icons"), { recursive: true });
mkdirSync(join(root, "assets/og"), { recursive: true });
copyFileSync(`public${OG_IMAGE_PATH}`, join(root, "assets/og/agentbase.png"));
for (const path of ["app/(en)/opengraph-image.alt.txt", "app/(ko)/ko/opengraph-image.alt.txt"]) writeFileSync(path, meta.ogAlt);
writeBrandPreview(root);
rmSync(join(root, "data"), { recursive: true, force: true });
cpSync("data", join(root, "data"), { recursive: true });
writeFileSync(join(root, "llms.txt"), renderLlmsTxt());
writeFileSync(join(root, "index.md"), renderMarkdown("en"));
mkdirSync(join(root, "ko"), { recursive: true });
writeFileSync(join(root, "ko/index.md"), renderMarkdown("ko"));

writeFileSync(join(root, "og-preview.html"), `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<meta name="robots" content="noindex,nofollow"><title>AgentBase — OG preview</title>
<style>
*{box-sizing:border-box}body{margin:0;background:#f3f3f1;color:#111;font-family:Arial,sans-serif}main{max-width:1280px;margin:auto;padding:32px 24px 64px}header{display:flex;align-items:center;justify-content:space-between;gap:24px;margin-bottom:24px}h1{font-size:24px;margin:0 0 8px}h2{font-size:16px;margin:36px 0 14px}p{margin:0;color:#555;line-height:1.5}a{color:inherit;text-underline-offset:4px}img{display:block;width:100%;height:auto;background:#fff}.artwork{border:1px solid #ccc}.share{width:min(100%,420px);border:1px solid #ccc;background:white}.share-copy{padding:16px}.domain{font-size:12px;text-transform:uppercase;letter-spacing:.06em}.share-title{font-size:17px;font-weight:700;margin:8px 0;color:#111}.share-description{font-size:14px}@media(max-width:600px){main{padding:20px 16px 40px}header{align-items:flex-start;flex-direction:column;gap:12px}h1{font-size:21px}}
</style></head><body><main><header><div><h1>AgentBase / Open Graph</h1><p>1200 × 630 px · PNG · English &amp; Korean pages</p></div><a href="c.html">View the landing page ↗</a></header>
<a href="assets/og/agentbase.png" aria-label="Open the full-size OG image"><img class="artwork" src="assets/og/agentbase.png" width="1200" height="630" alt="${escape(meta.ogAlt)}"></a>
<h2>Compact link preview</h2><div class="share"><img src="assets/og/agentbase.png" width="1200" height="630" alt="${escape(meta.ogAlt)}"><div class="share-copy"><p class="domain">agentba.se</p><p class="share-title">${escape(meta.ogTitle)}</p><p class="share-description">${escape(meta.description)}</p></div></div>
</main></body></html>`);
console.log("Synced C preview metadata, company schema, AI documents and OG artwork.");
